function T = thrust_aux(n, rho)
% 辅助推进器（侧推、垂推）推力计算（双向推力系数）
% 输入:
%   n   - 转速 (RPM)，正转=正向推力，反转=反向推力
%   rho - 水密度 (kg/m^3)
% 输出:
%   T   - 推力 (N)
%
% KT_fwd/KT_rev为非饱和段映射校准值（2026-06-21更新）
%   校准方案: [[推进器推力校准方案_20260621]] §3.4, 0616水池阶跃实验
%   校准方法: 20-80%非饱和阶跃段 → CFD阻力(300W)反推k → 80%参考RPM转KT
%   有效质量 m_y=210.6kg (刚性85.83+附加124.73)
%   时间常数: τ_exp≈2.5s, τ_cfd(线性化,0.2m/s)≈1.2s (exp比CFD快2×)
%   新CFD阻力(300W) Sway d1=1.67 d2=178.59
%   最大转速 2500 RPM, KT非固定值(随RPM变化), 当前取80%工作点
%   T1-T4 均为同型号 M060, 侧推标定结果统一复用
%   参考: k_Y_fwd(右)=0.001206, k_Y_rev(左)=0.000583 N/CAN-g

D_prop = 0.06;      % 辅助推直径 6cm
KT_fwd = 1.2531;    % 正向推力系数 (0616非饱和校准, 80%RPM_ref=1053, 右移/下沉)
KT_rev = 0.6193;    % 反向推力系数 (0616非饱和校准, 80%RPM_ref=1053, 左移/上浮)

n_rps = n / 60;     % rpm → rps
if n >= 0
    KT = KT_fwd;
else
    KT = KT_rev;
end
T = rho * D_prop^4 * KT * abs(n_rps) * n_rps;

end
